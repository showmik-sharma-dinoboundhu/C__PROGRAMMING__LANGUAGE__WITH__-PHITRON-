//FIRST HALF:
#include<stdio.h>
int main()
{
    int ss;
    scanf("%d",&ss);
    printf("%d",ss);

    return 0;
}

//SECOND HALF:
#include<stdio.h>
int main()
{
    int s,ss,ssd;
    scanf("%d %d %d",&s,&ss,&ssd);
    printf("%d %d %d",s,ss,ssd);

    return 0;
}


//int,float and char value print:
#include<stdio.h>
int main()
{
    int s;
    float ss;
    char ssd;
    scanf("%d %f %c",&s,&ss,&ssd);
    printf("%d %0.2f %c",s,ss,ssd);

    return 0;
}
